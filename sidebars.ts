import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

/**
 * Sidebar grouped like a reference book. Three fixed section headings (Bắt đầu,
 * Nội dung, Tra cứu); inside "Nội dung" each part is a collapsible row that
 * starts collapsed and opens when the reader enters one of its pages.
 * Part rows render as badge + title + chapter range (src/theme/DocSidebarItem/Category);
 * chapter and appendix links render a number badge, other links an icon
 * (src/theme/DocSidebarItem/Link, icons.ts).
 * Order inside a part comes from sidebar_position in each doc's front matter.
 */
const part = (label: string, dirName: string) => ({
  type: 'category' as const,
  label,
  className: 'book-part',
  collapsible: true,
  collapsed: true,
  items: [{type: 'autogenerated' as const, dirName}],
});

const sidebars: SidebarsConfig = {
  book: [
    {
      type: 'category',
      label: 'Bắt đầu',
      collapsible: false,
      items: ['table-of-contents', {type: 'autogenerated', dirName: 'introduction'}],
    },
    {
      type: 'category',
      label: 'Nội dung',
      collapsible: false,
      items: [
        part('Phần I. Nền tảng', 'foundations'),
        part('Phần II. Sản phẩm', 'products'),
        part('Phần III. Hệ thống', 'system'),
        part('Phần IV. Trí tuệ', 'intelligence'),
        part('Phần V. Tương lai', 'future'),
      ],
    },
    {
      type: 'category',
      label: 'Tra cứu',
      collapsible: false,
      items: ['glossary/index', {type: 'autogenerated', dirName: 'appendices'}, 'tools/index'],
    },
  ],
};

export default sidebars;
